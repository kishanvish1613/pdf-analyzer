"""
L4 Footer Reconstruction & Page Number Isolation Engine (E4, Phase 8B Task 6).
Recovers footer region and sub-blocks strictly below table bottom:
- Detects page numbers (e.g. "Page 1 of 4", "1 of 2", "Page 1")
- Detects generated / disclaimer text (e.g. "Statement Generated on...", "Kotak Mahindra Bank...")
- Anchors strictly to footer's own bbox
- Calculates gap metrics from table border / ink to footer ink and footer ink to page bottom.
"""

from __future__ import annotations
import re
from typing import List, Dict, Tuple, Optional, Any
import numpy as np

from pdf_analyzer.l0_bytes.primitives import PageByteLayer, PaintedTextChar
from pdf_analyzer.l4_layout.models import (
    TextSegment,
    TextLine,
    BlockType,
    HeaderBlock,
    FooterModel,
)

PAGE_NUMBER_REGEX = re.compile(
    r"^(?:page\s+)?(\d+)(?:\s*(?:of|/|-)\s*(\d+))?$",
    re.IGNORECASE,
)

DISCLAIMER_KEYWORDS = re.compile(
    r"(statement\s+generated|generated\s+on|computer\s+generated|disclaimer|terms\s+and\s+conditions|page\s+\d+|kotak|hdfc|sbi|bank\s+of\s+india|branch\s+copy|customer\s+copy)",
    re.IGNORECASE,
)


class FooterEngine:
    """
    Recovers footer region, sub-blocks, page numbers, and vertical gap metrics.
    """

    def build_footer_model(
        self,
        page_layer: PageByteLayer,
        table_bottom_y_pt: float,
        table_ink_min_y_pt: Optional[float] = None,
    ) -> FooterModel:
        """
        Builds the FooterModel for all content located strictly below the table bottom.
        """
        footer_chars = [
            c for c in page_layer.chars
            if c.origin_device_pt[1] <= table_bottom_y_pt - 1.0
        ]

        if not footer_chars:
            return FooterModel(
                footer_bbox_pt=(36.0, 0.0, page_layer.width_pt - 36.0, max(0.0, table_bottom_y_pt)),
                blocks=[],
                is_pinned=True,
                gap_table_ink_to_footer_ink_pt=0.0,
                gap_table_border_to_footer_ink_pt=0.0,
                gap_footer_ink_to_page_bottom_pt=0.0,
            )

        lines = self._build_lines_from_chars(footer_chars)
        if not lines:
            return FooterModel(
                footer_bbox_pt=(36.0, 0.0, page_layer.width_pt - 36.0, max(0.0, table_bottom_y_pt)),
                blocks=[],
                is_pinned=True,
                gap_table_ink_to_footer_ink_pt=0.0,
                gap_table_border_to_footer_ink_pt=0.0,
                gap_footer_ink_to_page_bottom_pt=0.0,
            )

        lines.sort(key=lambda l: l.baseline_y_pt, reverse=True)

        f_x0 = min(l.x0 for l in lines)
        f_y0 = min(l.y0 for l in lines)
        f_x1 = max(l.x1 for l in lines)
        f_y1 = max(l.y1 for l in lines)
        footer_bbox = (f_x0, f_y0, f_x1, f_y1)

        # Page number isolation and sub-block clustering
        page_num_text: Optional[str] = None
        page_num_bbox: Optional[Tuple[float, float, float, float]] = None
        other_lines: List[TextLine] = []

        for line in lines:
            txt = line.text.strip()
            # Strict page number check: must contain 'page' or be isolated bottom page counter
            if ("page" in txt.lower() and len(txt) < 30) or (PAGE_NUMBER_REGEX.match(txt) and "page" in txt.lower()):
                page_num_text = txt
                page_num_bbox = line.bbox_pt
            else:
                other_lines.append(line)

        # Partition lines into distinct semantic footer sub-regions:
        # 1. Statement Summary block
        # 2. Generated Info strip
        # 3. Standard disclaimer/footer lines
        summary_lines: List[TextLine] = []
        generated_lines: List[TextLine] = []
        disclaimer_lines: List[TextLine] = []

        has_summary_marker = any("statement summary" in l.text.lower() for l in other_lines)

        for line in other_lines:
            txt_lower = line.text.lower()
            if has_summary_marker and (
                any(k in txt_lower for k in ["statement summary", "opening balance", "dr count", "cr count", "debits", "credits", "closing bal"])
                or (line.baseline_y_pt >= 125.0 and not line.text.startswith("*"))
            ):
                summary_lines.append(line)
            elif any(k in txt_lower for k in ["generated on", "generated by", "requesting branch code", "branch code"]):
                generated_lines.append(line)
            else:
                disclaimer_lines.append(line)

        # Blocks creation
        blocks: List[HeaderBlock] = []
        if summary_lines:
            blocks.append(
                HeaderBlock(
                    block_id="statement_summary",
                    block_type=BlockType.SUMMARY_LINE,
                    bbox_pt=(
                        min(l.x0 for l in summary_lines),
                        min(l.y0 for l in summary_lines),
                        max(l.x1 for l in summary_lines),
                        max(l.y1 for l in summary_lines),
                    ),
                    lines=summary_lines,
                )
            )

        if generated_lines:
            blocks.append(
                HeaderBlock(
                    block_id="generated_info",
                    block_type=BlockType.INLINE_PAIRS,
                    bbox_pt=(
                        min(l.x0 for l in generated_lines),
                        min(l.y0 for l in generated_lines),
                        max(l.x1 for l in generated_lines),
                        max(l.y1 for l in generated_lines),
                    ),
                    lines=generated_lines,
                )
            )

        if disclaimer_lines:
            blocks.append(
                HeaderBlock(
                    block_id="footer_block_0",
                    block_type=BlockType.DISCLAIMER,
                    bbox_pt=(
                        min(l.x0 for l in disclaimer_lines),
                        min(l.y0 for l in disclaimer_lines),
                        max(l.x1 for l in disclaimer_lines),
                        max(l.y1 for l in disclaimer_lines),
                    ),
                    lines=disclaimer_lines,
                )
            )

        if page_num_text and page_num_bbox:
            blocks.append(
                HeaderBlock(
                    block_id="footer_page_num",
                    block_type=BlockType.PAGE_NUMBER,
                    bbox_pt=page_num_bbox,
                    lines=[l for l in lines if l.text.strip() == page_num_text],
                )
            )

        # Gap metrics
        highest_footer_y = f_y1
        lowest_footer_y = f_y0
        t_ink_y = table_ink_min_y_pt if table_ink_min_y_pt is not None else table_bottom_y_pt

        gap_table_border = max(0.0, table_bottom_y_pt - highest_footer_y)
        gap_table_ink = max(0.0, t_ink_y - highest_footer_y)
        gap_page_bottom = max(0.0, lowest_footer_y)

        # Pinned if bottom margin is within 72 pt of page bottom
        is_pinned = lowest_footer_y <= 72.0

        return FooterModel(
            footer_bbox_pt=footer_bbox,
            blocks=blocks,
            page_number_text=page_num_text,
            page_number_bbox_pt=page_num_bbox,
            is_pinned=is_pinned,
            gap_table_ink_to_footer_ink_pt=float(gap_table_ink),
            gap_table_border_to_footer_ink_pt=float(gap_table_border),
            gap_footer_ink_to_page_bottom_pt=float(gap_page_bottom),
        )

    def _build_lines_from_chars(self, chars: List[PaintedTextChar]) -> List[TextLine]:
        if not chars:
            return []

        # Cluster by baseline Y within 1.0 pt
        sorted_chars = sorted(chars, key=lambda c: c.origin_device_pt[1], reverse=True)
        baseline_groups: List[List[PaintedTextChar]] = []
        for c in sorted_chars:
            placed = False
            for group in baseline_groups:
                if abs(group[0].origin_device_pt[1] - c.origin_device_pt[1]) <= 1.0:
                    group.append(c)
                    placed = True
                    break
            if not placed:
                baseline_groups.append([c])

        lines: List[TextLine] = []
        line_counter = 0

        for group in baseline_groups:
            group.sort(key=lambda c: c.origin_device_pt[0])
            avg_base_y = float(np.mean([c.origin_device_pt[1] for c in group]))

            # Split horizontally into segments / sub-lines if horizontal gap > 20 pt
            chunks: List[List[PaintedTextChar]] = []
            curr_chunk: List[PaintedTextChar] = [group[0]]

            for c in group[1:]:
                prev = curr_chunk[-1]
                gap = c.font_bbox_device_pt[0] - prev.font_bbox_device_pt[2]
                if gap > 20.0:
                    chunks.append(curr_chunk)
                    curr_chunk = [c]
                else:
                    curr_chunk.append(c)
            if curr_chunk:
                chunks.append(curr_chunk)

            for chunk in chunks:
                txt_tokens = []
                for i, c in enumerate(chunk):
                    ch_txt = c.unicode_text or c.char_text
                    if i > 0:
                        prev = chunk[i - 1]
                        gap = c.origin_device_pt[0] - prev.font_bbox_device_pt[2]
                        if gap >= max(0.8, 0.0625 * prev.font_size_pt) and not ch_txt.startswith(" "):
                            txt_tokens.append(" ")
                    txt_tokens.append(ch_txt)
                txt = "".join(txt_tokens)

                x0 = min(c.font_bbox_device_pt[0] for c in chunk)
                y0 = min(c.font_bbox_device_pt[1] for c in chunk)
                x1 = max(c.font_bbox_device_pt[2] for c in chunk)
                y1 = max(c.font_bbox_device_pt[3] for c in chunk)

                seg = TextSegment(
                    text=txt,
                    bbox_pt=(x0, y0, x1, y1),
                    font_name=chunk[0].font_name,
                    font_size_pt=chunk[0].font_size_pt,
                    chars=chunk,
                )
                line = TextLine(
                    line_id=f"footer_line_{line_counter}",
                    segments=[seg],
                    baseline_y_pt=avg_base_y,
                    bbox_pt=(x0, y0, x1, y1),
                )
                lines.append(line)
                line_counter += 1

        return lines
